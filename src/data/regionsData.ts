// ==========================================
// FORMATTING AND CONVERSION UTILITIES
// ==========================================

export const formatCurrency = (amountInUSD: number, region: RegionCode = 'US'): string => {
  const cfg = REGIONS_DATA[region] || REGIONS_DATA.US;
  const localVal = amountInUSD * cfg.currency.rateFromUSD;

  if (cfg.currency.decimals === 0) {
    const formatted = Math.round(localVal).toLocaleString();
    return `${cfg.currency.symbol}${formatted}`;
  }

  const formatted = localVal.toLocaleString(undefined, {
    minimumFractionDigits: cfg.currency.decimals,
    maximumFractionDigits: cfg.currency.decimals,
  });

  return `${cfg.currency.symbol}${formatted}`;
};

export const formatWeight = (pounds: number, region: RegionCode = 'US'): string => {
  const cfg = REGIONS_DATA[region] || REGIONS_DATA.US;
  if (cfg.weightUnit === 'kg') {
    const kg = pounds * 0.453592;
    return `${kg.toFixed(1)} kg`;
  }
  return `${Math.round(pounds)} lbs`;
};

export const formatDistance = (miles: number, region: RegionCode = 'US'): string => {
  const cfg = REGIONS_DATA[region] || REGIONS_DATA.US;
  if (cfg.distanceUnit === 'km') {
    const km = miles * 1.60934;
    return `${km.toFixed(1)} km`;
  }
  return `${miles.toFixed(1)} miles`;
};
